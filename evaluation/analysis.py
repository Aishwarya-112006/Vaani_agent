"""
analysis.py  (QA-09)

Computes the 5 metrics required by Section 11 of the Master Guide from
evaluation/qa_independent_results.json (generated by `pytest` via the
results_recorder fixture in tests/conftest.py).

Usage:
    python evaluation/analysis.py
    (run from the repo root, or anywhere -- paths below are resolved
    relative to this file, not the current working directory)

Outputs:
    - Prints a summary table to stdout
    - Writes evaluation/metrics_summary.json (feeds RIME_EVIDENCE.md + the
      FE-09 evaluation dashboard page)

--- Fixes applied vs. the original QA-09 draft -----------------------------

1. RESULTS_PATH was pointing at evaluation/results.json -- the team's own
   self-authored file from issues #22/#24 (different schema entirely: a
   dict with generated_at/harness/scenario_count/... keys, not a list of
   {scenario_id, passed, ...} records). Running the old script against it
   throws TypeError immediately. Fixed to point at
   evaluation/qa_independent_results.json, which is what tests/conftest.py
   actually writes -- see the NOTE in that file for why the name differs
   from the team's.

2. total_count(ids) used to mean "how many of these IDs got recorded",
   not "how many scenarios are in this category". Since a scenario that
   fails its assert never reaches results_recorder.record() (the record
   call sits after the assertions, with no try/except), a failing
   scenario is *absent* from the results file rather than present with
   passed=False. The old total_count() then silently shrank the
   denominator to exclude every failure, so a category with 3 real
   failures and 0 recorded passes for those 3 would report a pass rate
   computed only over the survivors -- which can read as 100% even when
   the category is actually failing. Fixed by sourcing the canonical
   scenario list straight from scenarios.json (the fixed size of the
   T04-T20 etc. ranges) rather than from what happened to survive into
   the results file. A missing scenario now correctly counts as a failed
   attempt in the denominator, and its ID is listed explicitly per metric
   so it's traceable, not just a smaller number.

3. avg_interruption_recovery_latency_ms silently returned null with no
   explanation whenever no record had a latency_ms field -- which is
   always, since no test file in this suite currently records one. That
   made it look like a computed 0-sample average rather than an
   unmeasured metric. Fixed to say so explicitly via a paired *_note
   field, so RIME_EVIDENCE.md doesn't present "no data" as "we checked
   and it's fine".
-----------------------------------------------------------------------------
"""

import json
from pathlib import Path

SCENARIOS_PATH = Path(__file__).parent / "scenarios.json"
RESULTS_PATH = Path(__file__).parent / "qa_independent_results.json"
SUMMARY_PATH = Path(__file__).parent / "metrics_summary.json"

# Categories that feed each metric, per Section 11 of the Master Guide.
# CANCEL-EXTRA-1/2 (QA's own additions beyond the canonical T01-T25 set)
# are deliberately excluded from these metrics -- they're extra
# regression coverage, not part of the scored suite scenarios.json
# defines. Only IDs actually present in scenarios.json count here.
METRIC_CATEGORIES = {
    "REFINE": "interrupt",
    "CANCEL": "interrupt",
    "STATUS": "interrupt",
    "PIVOT": "interrupt",
}


def load_scenarios() -> dict[str, str]:
    """Return {scenario_id: type} for every canonical scenario, straight
    from scenarios.json -- the single source of truth for which IDs exist
    and what category they belong to, instead of hardcoded ID ranges that
    can silently drift out of sync if scenarios.json ever changes."""
    if not SCENARIOS_PATH.exists():
        raise SystemExit(f"No scenarios.json found at {SCENARIOS_PATH}.")
    with open(SCENARIOS_PATH) as f:
        scenarios = json.load(f)
    return {s["id"]: s["type"] for s in scenarios}


def load_results() -> list[dict]:
    if not RESULTS_PATH.exists():
        raise SystemExit(
            f"No qa_independent_results.json found at {RESULTS_PATH}.\n"
            f"Run `python -m pytest tests/ -v` from the repo root first (QA-08)."
        )
    with open(RESULTS_PATH) as f:
        return json.load(f)


def compute_metrics(scenario_types: dict[str, str], records: list[dict]) -> dict:
    by_id: dict[str, list[dict]] = {}
    for r in records:
        by_id.setdefault(r["scenario_id"], []).append(r)

    def ids_of(*types: str) -> list[str]:
        # Sorted so output/order is stable across runs, not dict-iteration order.
        return sorted(sid for sid, t in scenario_types.items() if t in types)

    def passed_count(ids: list[str]) -> int:
        return sum(
            1 for sid in ids if sid in by_id and all(rec.get("passed") for rec in by_id[sid])
        )

    def missing_ids(ids: list[str]) -> list[str]:
        # Absent from the results file entirely -- almost always means the
        # test raised on an assert before reaching results_recorder.record(),
        # i.e. a real failure, not a scenario that was never run.
        return [sid for sid in ids if sid not in by_id]

    def rate(correct: int, total: int) -> float | None:
        return round(correct / total * 100, 1) if total else None

    metrics: dict = {}

    # 1. Interrupt Detection Accuracy (T04-T20: REFINE+CANCEL+STATUS+PIVOT)
    interrupt_ids = ids_of("REFINE", "CANCEL", "STATUS", "PIVOT")
    interrupt_total = len(interrupt_ids)
    interrupt_correct = passed_count(interrupt_ids)
    metrics["interrupt_detection_accuracy_pct"] = rate(interrupt_correct, interrupt_total)
    metrics["interrupt_detection_sample"] = f"{interrupt_correct}/{interrupt_total}"
    metrics["interrupt_detection_missing_ids"] = missing_ids(interrupt_ids)

    # 2. Stale Response Block Rate (T21-T23) -- MUST be 100%
    stale_ids = ids_of("STALE")
    stale_total = len(stale_ids)
    stale_blocked = passed_count(stale_ids)
    metrics["stale_response_block_rate_pct"] = rate(stale_blocked, stale_total)
    metrics["stale_block_sample"] = f"{stale_blocked}/{stale_total}"
    metrics["stale_block_missing_ids"] = missing_ids(stale_ids)

    # 3. Context Preservation Rate (T04-T20) -- reused as a proxy from the
    # interrupt pass/fail set, same as the original draft, since no test
    # file currently records a dedicated context_correct field. Flagged
    # explicitly as a proxy rather than a distinct measurement.
    metrics["context_preservation_rate_pct"] = metrics["interrupt_detection_accuracy_pct"]
    metrics["context_preservation_sample"] = metrics["interrupt_detection_sample"]
    metrics["context_preservation_note"] = (
        "proxy metric -- reuses interrupt_detection_accuracy_pct; no test "
        "file currently records a dedicated context_correct field"
    )

    # 4. Interruption Recovery Latency (T04-T20), from latency_ms field if present
    latencies = [
        rec["latency_ms"]
        for sid in interrupt_ids
        for rec in by_id.get(sid, [])
        if "latency_ms" in rec
    ]
    if latencies:
        metrics["avg_interruption_recovery_latency_ms"] = round(sum(latencies) / len(latencies), 1)
        metrics["avg_interruption_recovery_latency_ms_note"] = None
    else:
        metrics["avg_interruption_recovery_latency_ms"] = None
        metrics["avg_interruption_recovery_latency_ms_note"] = (
            "not measured -- no test file in this suite currently records a "
            "latency_ms field on results_recorder.record(); this is an "
            "unmeasured metric, not a computed 0-sample average"
        )

    # 5. STATUS Non-Cancellation Rate (T15-T17) -- MUST be 100%
    status_ids = ids_of("STATUS")
    status_total = len(status_ids)
    status_correct = passed_count(status_ids)
    metrics["status_non_cancellation_rate_pct"] = rate(status_correct, status_total)
    metrics["status_non_cancellation_sample"] = f"{status_correct}/{status_total}"
    metrics["status_non_cancellation_missing_ids"] = missing_ids(status_ids)

    metrics["note"] = "Small sample, exploratory -- see RIME_EVIDENCE.md limitations section."
    return metrics


def main():
    scenario_types = load_scenarios()
    records = load_results()
    metrics = compute_metrics(scenario_types, records)

    print("\n=== VaaniAgent Evaluation Metrics (QA-independent run) ===\n")
    for key, value in metrics.items():
        print(f"{key:45s}: {value}")

    with open(SUMMARY_PATH, "w") as f:
        json.dump(metrics, f, indent=2)
    print(f"\nSaved to {SUMMARY_PATH}")


if __name__ == "__main__":
    main()